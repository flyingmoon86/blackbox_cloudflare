def get_page_texts(profile):
    try:
        overrides = json.loads(profile.page_texts or "{}") if profile else {}
    except (ValueError, TypeError):
        overrides = {}
    if not isinstance(overrides, dict):
        overrides = {}
    return {key: overrides.get(key, default) if isinstance(overrides.get(key, default), str) else default
            for key, (_, _, default) in PAGE_TEXTS.items()}
